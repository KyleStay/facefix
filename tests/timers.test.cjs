const {test} = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const view = vm.runInNewContext(fs.readFileSync(require.resolve('../connection.js'),'utf8') + '\n' + fs.readFileSync(require.resolve('../timers.js'),'utf8') + '\nFacefixTimers;');
test('timer view distinguishes running, armed, paused, ended, and unavailable states', () => {
  const fields = new Map();
  const root = {querySelector: selector => { if (!fields.has(selector)) fields.set(selector, {}); return fields.get(selector); }};
  const field = key => root.querySelector(`[data-timer="${key}"]`);
  const state = {schema:1, enabled:true, away:false, navigationMs:2750, recoveryMs:13750, reason:'running', postMatched:true};
  view.render(root,state);
  assert.equal(field('navigation').textContent,'2.8 s');
  assert.equal(field('recovery').textContent,'13.8 s');
  assert.equal(field('navigation-progress').value,2750);
  assert.match(field('note').textContent,/Tracking a visible post/);
  view.render(root,{...state,away:true});
  assert.equal(field('navigation').textContent,'Armed');
  view.render(root,{...state,enabled:false});
  assert.equal(field('navigation').textContent,'Paused');
  view.render(root,{...state,navigationMs:0,recoveryMs:0,reason:'interaction'});
  assert.match(field('state').textContent,/interaction/);
  view.render(root,{...state,navigationMs:0,recoveryMs:0,reason:'finished'});
  assert.match(field('state').textContent,/finished/);
  view.render(root,null);
  assert.equal(field('navigation').textContent,'—');
  assert.match(field('state').textContent,/Connection check failed/);
  view.render(root,{...state,recoveryMs:Infinity});
  assert.match(field('state').textContent,/Connection check failed/);
});
