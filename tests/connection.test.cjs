const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const check=vm.runInNewContext(fs.readFileSync(require.resolve('../connection.js'),'utf8')+'\nFacefixConnection;',{URL,setTimeout,clearTimeout});
const snapshot={schema:1,guardVersion:'1.4.0',enabled:true,away:false,navigationMs:0,recoveryMs:0};
test('connection distinguishes wrong tab, missing access, old scripts, missing guard, and working guard',async()=>{
  let response={bridge:true,bridgeVersion:'1.4.0',guard:snapshot};
  let fail=false, calls=0;
  const chrome={runtime:{getManifest:()=>({version:'1.4.0'})},tabs:{async sendMessage(id,message,options){calls++;assert.equal(options.frameId,0);if(fail)throw Error('No receiver');return response;}}};
  const tab={id:1,url:'https://www.facebook.com/'};
  assert.equal((await check.inspect(chrome,{id:1,url:'https://example.org/'})).kind,'wrong-tab');
  assert.equal((await check.inspect(chrome,{id:1})).kind,'no-access');
  assert.equal((await check.inspect(chrome,{...tab,discarded:true})).kind,'discarded');
  assert.equal((await check.inspect(chrome,{...tab,status:'loading'})).kind,'loading');
  assert.equal(calls,0,'unavailable tabs are not messaged');
  assert.equal((await check.inspect(chrome,tab)).kind,'connected');
  response={...response,guard:null};
  assert.equal((await check.inspect(chrome,tab)).kind,'guard-missing');
  response={...snapshot,guardVersion:'1.3.0'};
  assert.equal((await check.inspect(chrome,tab)).kind,'outdated','legacy status is recognized');
  response={bridge:true,bridgeVersion:'1.3.0',guard:snapshot};
  assert.equal((await check.inspect(chrome,tab)).kind,'outdated','old isolated script detected separately');
  response={bridge:true,bridgeVersion:'1.4.0',guard:{...snapshot,recoveryMs:Infinity}};
  assert.equal((await check.inspect(chrome,tab)).kind,'guard-missing');
  response={arbitrary:'value'};
  assert.equal((await check.inspect(chrome,tab)).kind,'incompatible');
  fail=true;
  assert.equal((await check.inspect(chrome,tab)).kind,'bridge-missing');
  assert.equal(check.matches('https://facebook.com.attacker.test/'),false);
  assert.equal(check.matches('http://facebook.com/'),false);
});
